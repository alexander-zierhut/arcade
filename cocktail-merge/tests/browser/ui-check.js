// tests/browser/ui-check.js: screenshots of every DOM overlay and the HUD (a review tool, not a test).
// Run: node tests/browser/ui-check.js
// 1. Regenerates tests/browser/ui-check.html from the DOM shell of index.html (between the ui-shell
//    markers), so the harness never drifts from the real page. The harness loads only config,
//    projection, the art files and src/ui/*, fakes CM.app.ctx and shows one state per ?show=...
// 2. Shoots docs/preview/ui-check-<state>-<w>x<h>.png at 390x844 (phone) and 1280x800 (desktop).
// 3. Loads index.html itself and reports the boot-guard card (expected while app files are missing).
// Exits 1 on page errors or console errors in the harness.
'use strict';
var fs = require('fs');
var path = require('path');
var url = require('url');
var chrome = require('./chrome.js');

var ROOT = path.resolve(__dirname, '..', '..');
var OUT = path.join(ROOT, 'docs', 'preview');
var HARNESS = path.join(__dirname, 'ui-check.html');
var STATES = ['title', 'title-run', 'pause', 'win', 'over', 'oops', 'rotate', 'play', 'settings', 'collection', 'howto', 'armed'];
var SIZES = [[390, 844, 2, 1], [1280, 800, 1, 0], [375, 667, 2, 1]];

function generate() {
  var html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  var a = html.indexOf('<!-- ui-shell-begin'), b = html.indexOf('<!-- ui-shell-end -->');
  if (a < 0 || b < 0) throw new Error('index.html lacks the ui-shell markers');
  var shell = html.slice(html.indexOf('-->', a) + 3, b);
  var art = ['glass', 'garnish', 'tier1-shot', 'tier2-oldfashioned', 'tier3-cosmo', 'tier4-mojito', 'tier5-margarita',
    'tier6-sunrise', 'tier7-pinacolada', 'tier8-coconut', 'tier9-sangria-verde', 'coin', 'scenery', 'overrides', 'sprites'];
  if (fs.existsSync(path.join(ROOT, 'src/art/backgrounds.js'))) art.push('backgrounds');
  var scripts = ['dedication', 'config', 'projection'].map(function (f) { return 'src/' + f + '.js'; })
    .concat(art.map(function (f) { return 'src/art/' + f + '.js'; }))
    .concat(['storage', 'input', 'hud', 'overlays'].map(function (f) { return 'src/ui/' + f + '.js'; }));
  var out = [
    '<!doctype html>',
    '<!-- GENERATED by tests/browser/ui-check.js from index.html; do not edit by hand. -->',
    '<html lang="en"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">',
    '<title>UI check</title>',
    '<link rel="stylesheet" href="../../src/style/base.css">',
    '<link rel="stylesheet" href="../../src/style/hud.css">',
    '<link rel="stylesheet" href="../../src/style/overlays.css">',
    '</head><body>', shell
  ].concat(scripts.map(function (s) { return '<script src="../../' + s + '"></script>'; }))
    .concat(['<script src="ui-check-page.js"></script>', '</body></html>', '']);
  fs.writeFileSync(HARNESS, out.join('\n'));
}

async function main() {
  generate();
  fs.mkdirSync(OUT, { recursive: true });
  var browser = await chrome.launchChrome();
  var errors = [];
  try {
    for (var si = 0; si < SIZES.length; si++) {
      var sz = SIZES[si];
      for (var i = 0; i < STATES.length; i++) {
        if (si === 2 && ['title', 'title-run', 'pause', 'play'].indexOf(STATES[i]) < 0) continue;
        var page = await browser.newPage({ viewport: { width: sz[0], height: sz[1] }, deviceScaleFactor: sz[2],
          hasTouch: !!sz[3], isMobile: !!sz[3] });
        var tag = STATES[i] + '-' + sz[0] + 'x' + sz[1];
        page.on('pageerror', function (e) { errors.push('[' + tag + '] ' + (e && e.stack || e)); });
        page.on('console', function (m) { if (m.type() === 'error') errors.push('[' + tag + '] ' + m.text()); });
        await page.goto(url.pathToFileURL(HARNESS).href + '?show=' + STATES[i] + '&coarse=' + sz[3], { waitUntil: 'load' });
        await page.waitForSelector('body[data-done="1"]', { timeout: 10000 });
        await page.waitForTimeout(700);
        var file = path.join(OUT, 'ui-check-' + tag + '.png');
        await page.screenshot({ path: file });
        var report = await page.evaluate(function () { return window.uiReport ? window.uiReport() : ''; });
        console.log('wrote ' + path.relative(ROOT, file) + (report ? '  ' + report : ''));
        await page.close();
      }
    }
    var p = await browser.newPage({ viewport: { width: 390, height: 844 } });
    await p.goto(url.pathToFileURL(path.join(ROOT, 'index.html')).href, { waitUntil: 'load' });
    var card = await p.evaluate(function () { var c = document.querySelector('.boot-card'); return c ? c.innerText : '(no boot card: game booted)'; });
    await p.screenshot({ path: path.join(OUT, 'ui-check-index-390x844.png') });
    console.log('index.html: ' + card.replace(/\n+/g, ' | '));
    await p.close();
  } finally {
    await browser.close();
  }
  if (errors.length) { console.error('Problems:\n  ' + errors.join('\n  ')); process.exit(1); }
}

main().catch(function (e) { console.error(e && e.stack || e); process.exit(1); });
