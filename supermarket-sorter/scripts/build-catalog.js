#!/usr/bin/env node
// scripts/build-catalog.js: merges assets/items/manifest/*.json into src/art/catalog.js (committed; the game has no build step).
// Usage: node scripts/build-catalog.js
'use strict';
var fs = require('fs'), path = require('path');
var ROOT = path.resolve(__dirname, '..');
var DIR = path.join(ROOT, 'assets', 'items', 'manifest');
var OUT = path.join(ROOT, 'src', 'art', 'catalog.js');
var items = [], seen = {};
// tier 1 = tasty food (preferred by the level skin: she likes looking at food), 2 = drinks and pantry, 3 = non-food
var TIER1 = ['bakery', 'breakfast', 'brotzeit', 'candy', 'cheese', 'cookies', 'dairy', 'deli', 'frozen', 'fruits', 'molkerei', 'noodles', 'nuts', 'produce', 'seafood', 'snacks', 'spreads', 'suesses', 'treats', 'veggies', 'world', 'yogurt', 'cereal',
  'burger', 'pizza', 'kuchen', 'eis', 'schoko', 'bonbons', 'broetchen', 'kaese', 'obst', 'beeren', 'gemuese', 'fruehstueck', 'asia', 'mexiko', 'grill', 'suppen', 'gebaeck', 'knabber', 'shakes', 'frisch'];
var TIER3 = ['household', 'cleaning', 'paper', 'bath', 'care', 'pet', 'baby', 'plants'];
function tierOf(cat) { return TIER1.indexOf(cat) >= 0 ? 1 : TIER3.indexOf(cat) >= 0 ? 3 : 2; }
var geometry = {}, geometry2d = {}, overrides = {};
try { geometry = JSON.parse(fs.readFileSync(path.join(DIR, 'geometry.json'), 'utf8')); } catch (e) { geometry = {}; }
try { geometry2d = JSON.parse(fs.readFileSync(path.join(DIR, 'geometry-2d.json'), 'utf8')); } catch (e) { geometry2d = {}; }     // the flat (v0.3.0) set in assets/items-2d
try { overrides = JSON.parse(fs.readFileSync(path.join(DIR, 'silhouette-overrides.json'), 'utf8')); } catch (e) { overrides = {}; }
function hue(hex) {
  var m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex || '');
  if (!m) return -1;
  var r = parseInt(m[1], 16) / 255, g = parseInt(m[2], 16) / 255, b = parseInt(m[3], 16) / 255;
  var max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min, h = 0;
  if (d < 0.08 || max < 0.15) return -1;                                   // greys, blacks, whites: no hue
  if (max === r) h = ((g - b) / d) % 6; else if (max === g) h = (b - r) / d + 2; else h = (r - g) / d + 4;
  h = Math.round(h * 60); if (h < 0) h += 360;
  return h;
}
if (fs.existsSync(DIR)) {
  fs.readdirSync(DIR).filter(function (f) { return /\.json$/.test(f) && f !== 'geometry.json' && f !== 'geometry-2d.json' && f !== 'silhouette-overrides.json'; }).sort().forEach(function (f) {
    var m = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
    (m.items || []).forEach(function (it) {
      if (seen[it.id]) { console.error('duplicate id ' + it.id + ' in ' + f); process.exitCode = 1; return; }
      if (!fs.existsSync(path.join(ROOT, 'assets', 'items', it.file))) { console.error('missing file for ' + it.id); process.exitCode = 1; return; }
      seen[it.id] = 1;
      var geo = geometry[it.id], geo2 = geometry2d[it.id], aspect = geo ? Math.round(geo.h / geo.w * 4) / 4 : 0;
      var ov = overrides[it.id] || {};
      items.push({ id: it.id, name: it.name, category: m.category, cls: it['class'], color: it.color, accent: it.accent, label: it.label || '', icon: it.icon || '',
        hue: hue(it.color), shapeGroup: ov.shapeGroup || (it['class'] + (aspect ? '@' + aspect : '')), silhouetteOk: ov.silhouetteOk !== false, tier: tierOf(m.category),
        w: geo ? geo.w : 0, h: geo ? geo.h : 0, w2: geo2 ? geo2.w : 0, h2: geo2 ? geo2.h : 0 });                 // measured bounding box in viewBox units (sprites.js scales every product to the same slot width)
    });
  });
}
var src = '// src/art/catalog.js: GENERATED by scripts/build-catalog.js from assets/items/manifest/*.json. Do not edit by hand.\n' +
  '(function (root) {\n  \'use strict\';\n  var SS = root.SS = root.SS || {};\n' +
  '  var items = ' + JSON.stringify(items) + ';\n' +
  '  var byId = {};\n  for (var i = 0; i < items.length; i++) byId[items[i].id] = items[i];\n' +
  '  var catalog = { items: items, byId: byId, ids: items.map(function (it) { return it.id; }) };\n' +
  '  SS.catalog = catalog;\n  if (typeof module !== \'undefined\' && module.exports) module.exports = catalog;\n' +
  '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';
fs.writeFileSync(OUT, src);
console.log('catalog: ' + items.length + ' products -> ' + path.relative(ROOT, OUT));
