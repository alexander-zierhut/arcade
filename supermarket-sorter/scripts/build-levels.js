#!/usr/bin/env node
// scripts/build-levels.js: bakes levels with witnesses into src/game/levels-data.js (DESIGN 3.3, 3.7).
// Usage: node scripts/build-levels.js [count=60] [mode=both] [--no-windows] [--windows-until=N] [--fresh]
// Each level is dealt, gated (solver + playouts), verified through the board rules and, with windows on, held to the
// acceptance windows (agent win rate) and shortened. Results are cached in scripts/.cache/<mode>-<n>-<gen>.json.
'use strict';
var fs = require('fs'), path = require('path');
var ROOT = path.resolve(__dirname, '..');
var C = require(path.join(ROOT, 'src/config.js'));
var RNG = require(path.join(ROOT, 'src/game/rng.js'));
var B = require(path.join(ROOT, 'src/game/board.js'));
var SOL = require(path.join(ROOT, 'src/game/solver.js'));
var GEN = require(path.join(ROOT, 'src/game/gen.js'));
var LV = require(path.join(ROOT, 'src/game/levels.js'));
var args = process.argv.slice(2);
var COUNT = parseInt(args[0], 10) || 60, MODE = args[1] && args[1] !== 'both' ? [args[1]] : ['timed', 'relaxed'];
var WINDOWS = args.indexOf('--no-windows') < 0, FRESH = args.indexOf('--fresh') >= 0;
var WU = args.filter(function (a) { return /^--windows-until=\d+$/.test(a); })[0];
var WINDOWS_UNTIL = WU ? parseInt(WU.split('=')[1], 10) : 1e9;   // acceptance windows only up to this level (deep boards rarely meet them)
var CACHE = path.join(__dirname, '.cache');
if (!fs.existsSync(CACHE)) fs.mkdirSync(CACHE, { recursive: true });
var OUT = path.join(ROOT, 'src/game/levels-data.js');

function bake(mode, n) {
  var useWindows = WINDOWS && n >= 7 && n <= WINDOWS_UNTIL;
  var key = path.join(CACHE, mode + '-' + n + '-g' + C.GEN_VERSION + (useWindows ? 'w' : '') + '.json');
  if (!FRESH && fs.existsSync(key)) return JSON.parse(fs.readFileSync(key, 'utf8'));
  var t0 = Date.now(), rec;
  var a = LV.authored(n);
  if (a) {
    var g = GEN.gate(a, 500000, 128, RNG.create('authored-' + n));
    if (!g) throw new Error('authored level ' + n + ' failed the gate');
    var w = GEN.shorten(a, g.witness, RNG.create('authored-short-' + n), 63);
    a.par = Math.ceil(1.25 * w.length);
    rec = { str: LV.encode(a, w), attempt: 0, relax: 0, rate: Math.round(GEN.winRate(a, RNG.create('authored-win-' + n), 40) * 100), nodes: g.nodes, witness: w.length, items: a.items, ms: Date.now() - t0, source: 'authored' };
  } else {
    var r = GEN.generate(mode, n, { attempts: 120, nodes: 400000, playouts: 200, windows: useWindows });
    if (!r) { r = GEN.generate(mode, n, { attempts: 60, nodes: 400000, playouts: 200, windows: false }); if (!r) throw new Error(mode + ' L' + n + ': no level found'); r.windowMiss = true; }
    rec = { str: LV.encode(r.level, r.witness), attempt: r.attempt, relax: r.relax, rate: r.rate, nodes: r.nodes, witness: r.witness.length, items: r.level.items, ms: Date.now() - t0, source: 'generated', windowMiss: !!r.windowMiss };
  }
  var d = LV.decode(rec.str);
  var v = SOL.verify(B.createBoard(d.level), d.witness);
  if (!v.ok) throw new Error(mode + ' L' + n + ': encoded witness fails: ' + v.reason);
  fs.writeFileSync(key, JSON.stringify(rec));
  return rec;
}

var data = { v: 2, gen: C.GEN_VERSION, timed: [], relaxed: [] }, stats = [];
MODE.forEach(function (mode) {
  var start = Date.now();
  for (var n = 1; n <= COUNT; n++) {
    var rec = bake(mode, n);
    data[mode].push(rec.str);
    stats.push({ mode: mode, n: n, rec: rec });
    if (n % 10 === 0 || n === COUNT) process.stdout.write(mode + ' L' + n + ' (' + Math.round((Date.now() - start) / 1000) + ' s)\n');
  }
});
if (MODE.length === 1) {                      // keep the other mode from the existing file
  try { var old = require(OUT).LEVEL_DATA; var other = MODE[0] === 'timed' ? 'relaxed' : 'timed'; data[other] = old[other] || []; } catch (e) { /* none */ }
}
var src = '// src/game/levels-data.js: GENERATED by scripts/build-levels.js. Do not edit. One string per level: shape|tag|n|par|locks|belts|rack|witness.\n' +
  '(function (root) {\n  \'use strict\';\n  var SS = root.SS = root.SS || {};\n  var LEVEL_DATA = {\n    v: 2, gen: ' + C.GEN_VERSION + ',\n' +
  '    timed: [\n' + data.timed.map(function (s) { return '      ' + JSON.stringify(s); }).join(',\n') + '\n    ],\n' +
  '    relaxed: [\n' + data.relaxed.map(function (s) { return '      ' + JSON.stringify(s); }).join(',\n') + '\n    ]\n  };\n' +
  '  SS.LEVEL_DATA = LEVEL_DATA;\n  if (typeof module !== \'undefined\' && module.exports) module.exports = { LEVEL_DATA: LEVEL_DATA };\n' +
  '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';
fs.writeFileSync(OUT, src);
var misses = stats.filter(function (s) { return s.rec.windowMiss; }), relaxed = stats.filter(function (s) { return s.rec.relax > 0; });
console.log('levels-data.js: ' + data.timed.length + ' timed + ' + data.relaxed.length + ' relaxed levels, ' + Math.round(fs.statSync(OUT).size / 1024) + ' KB');
console.log('window misses: ' + misses.length + (misses.length ? ' (' + misses.map(function (s) { return s.mode + s.n; }).join(' ') + ')' : '') + '; relaxed ladder used: ' + relaxed.length + (relaxed.length ? ' (' + relaxed.map(function (s) { return s.mode + s.n + ':' + s.rec.relax; }).join(' ') + ')' : ''));
var rates = stats.map(function (s) { return s.rec.rate; }).filter(function (r) { return r >= 0; });
console.log('agent win rates: ' + stats.filter(function (s) { return s.n <= 12; }).map(function (s) { return s.mode[0] + s.n + ':' + s.rec.rate; }).join(' ') + ' ...');
