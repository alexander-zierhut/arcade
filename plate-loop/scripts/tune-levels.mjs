// scripts/tune-levels.mjs: the tuning pass (plan 5.7). Plays every fixed level (1-500) with the bot at two skill levels,
// greedy and sloppy, 3 seeds each, and prints per level: tier, minimal moves, tightness, greedy win rate, sloppy win rate.
// Flags levels whose greedy win rate contradicts the tier (easy < 60 %, extreme > 60 %); it only reports, it never re-tiers.
// Also writes the report to docs/levels-tuning.md.
//   node scripts/tune-levels.mjs            all levels
//   node scripts/tune-levels.mjs 101-200    just a range (prints, does not write the report)
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (p) => join(root, 'src', p);
const layouts = require(src('levels/layouts.js'));
const solver = require(src('gen/solver.js'));
const gen = require(src('gen/generator.js'));
const bot = require(src('gen/bot.js'));
require(src('levels/levels-001-100.js'));
const levels = require(src('levels/levels-101-500.js'));

const SEEDS = [1, 2, 3];
const EASY_MIN = 0.6, EXTREME_MAX = 0.6;
const TIERS = ['easy', 'normal', 'hard', 'extreme'];
const range = (process.argv[2] || '').match(/^(\d+)-(\d+)$/);
const lo = range ? Number(range[1]) : 1, hi = range ? Number(range[2]) : levels.length;

const rate = (level, layout, skill) => {
  let won = 0;
  for (const seed of SEEDS) if (bot.play(level, { layout, skill, seed }).won) won++;
  return won / SEEDS.length;
};
const pct = (x) => Math.round(x * 100);

const t0 = Date.now(), rows = [];
for (const level of levels) {
  if (level.id < lo || level.id > hi) continue;
  const layout = layouts[level.layout], sol = solver.solve(level, { layout });
  const m = gen.metrics(level, sol.moves, layout);
  rows.push({ id: level.id, tier: level.tier, N: level.N, moves: m.moves, tight: m.tightness, greedy: rate(level, layout, 'greedy'), sloppy: rate(level, layout, 'sloppy') });
}

const mean = (a) => a.length ? a.reduce((s, x) => s + x, 0) / a.length : 0;
const flagged = rows.filter((r) => (r.tier === 'easy' && r.greedy < EASY_MIN) || (r.tier === 'extreme' && r.greedy > EXTREME_MAX));
const summary = TIERS.map((t) => {
  const rs = rows.filter((r) => r.tier === t);
  return { tier: t, n: rs.length, moves: mean(rs.map((r) => r.moves)), tight: mean(rs.map((r) => r.tight)), greedy: mean(rs.map((r) => r.greedy)), sloppy: mean(rs.map((r) => r.sloppy)) };
}).filter((s) => s.n);

const lines = [];
lines.push('# Plate Loop: level tuning report', '');
lines.push('Generated by `node scripts/tune-levels.mjs` (plan 5.7). Every level is played by `bot.play` at two skill levels,');
lines.push('3 seeds each (' + SEEDS.join(', ') + '): **greedy** (taps the best-looking box, only on an empty belt) and **sloppy**');
lines.push('(30 % random taps, sometimes taps with pieces in flight, taps again after 0.1-0.8 s). Win rate = wins / 3.');
lines.push('Nothing is re-tiered automatically; the flags are for a human to look at.', '');
lines.push('## Per tier (levels ' + lo + '-' + hi + ')', '');
lines.push('| tier | levels | mean moves | mean tightness | mean greedy win | mean sloppy win |', '|---|---|---|---|---|---|');
for (const s of summary) lines.push('| ' + [s.tier, s.n, s.moves.toFixed(1), s.tight.toFixed(2), pct(s.greedy) + ' %', pct(s.sloppy) + ' %'].join(' | ') + ' |');
lines.push('', '## Flagged (greedy win rate contradicts the tier: easy < ' + pct(EASY_MIN) + ' %, extreme > ' + pct(EXTREME_MAX) + ' %)', '');
if (!flagged.length) lines.push('None.');
else {
  lines.push('| level | tier | N | moves | tightness | greedy | sloppy |', '|---|---|---|---|---|---|---|');
  for (const r of flagged) lines.push('| ' + [r.id, r.tier, r.N, r.moves, r.tight.toFixed(2), pct(r.greedy) + ' %', pct(r.sloppy) + ' %'].join(' | ') + ' |');
}
lines.push('', '## All levels', '');
lines.push('| level | tier | N | moves | tightness | greedy | sloppy |', '|---|---|---|---|---|---|---|');
for (const r of rows) lines.push('| ' + [r.id, r.tier, r.N, r.moves, r.tight.toFixed(2), pct(r.greedy) + ' %', pct(r.sloppy) + ' %'].join(' | ') + ' |');
lines.push('');

// console: the per-level table, then the summary and the flags at the end
const head = ['id', 'tier', 'N', 'moves', 'tight', 'greedy', 'sloppy'];
const body = rows.map((r) => [r.id, r.tier, r.N, r.moves, r.tight.toFixed(2), pct(r.greedy) + '%', pct(r.sloppy) + '%']);
const widths = head.map((h, i) => Math.max(h.length, ...body.map((r) => String(r[i]).length)));
const fmt = (r) => r.map((c, i) => String(c).padEnd(widths[i])).join('  ');
console.log(fmt(head));
body.forEach((r) => console.log(fmt(r)));
console.log('');
for (const s of summary) console.log(s.tier.padEnd(8) + s.n + ' levels, mean moves ' + s.moves.toFixed(1) + ', tightness ' + s.tight.toFixed(2) + ', greedy ' + pct(s.greedy) + '%, sloppy ' + pct(s.sloppy) + '%');
console.log(flagged.length + ' flagged (easy greedy < ' + pct(EASY_MIN) + '%, extreme greedy > ' + pct(EXTREME_MAX) + '%)');
if (flagged.length) {
  const fh = ['id', 'tier', 'N', 'moves', 'tight', 'greedy', 'sloppy'];
  const fb = flagged.map((r) => [r.id, r.tier, r.N, r.moves, r.tight.toFixed(2), pct(r.greedy) + '%', pct(r.sloppy) + '%']);
  const fw = fh.map((h, i) => Math.max(h.length, ...fb.map((r) => String(r[i]).length)));
  const ff = (r) => r.map((c, i) => String(c).padEnd(fw[i])).join('  ');
  console.log(ff(fh));
  fb.forEach((r) => console.log(ff(r)));
}
console.log((Date.now() - t0) + ' ms');
if (!range) { writeFileSync(join(root, 'docs', 'levels-tuning.md'), lines.join('\n')); console.log('wrote docs/levels-tuning.md'); }
